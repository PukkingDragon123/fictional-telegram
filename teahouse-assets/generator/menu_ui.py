def _set(font, s, space, gap, kern, height):
    """Lay a string out: returns a bool mask (height x width)."""
    cols = []
    x = 0
    prev = None
    placed = []
    for ch in s:
        if ch == ' ':
            x += space
            prev = ' '
            continue
        g = font.get(ch)
        if g is None:
            g = font.get(ch.upper()) if ch.upper() in font else font.get(ch.lower())
        if g is None:
            x += space
            continue
        if prev is not None:
            x += gap + kern.get((prev, ch), 0)
            if prev != ' ':
                pass
        placed.append((x, g))
        x += g.shape[1]
        prev = ch
    w = max([px + g.shape[1] for px, g in placed] + [1])
    m = np.zeros((height, w), bool)
    for px, g in placed:
        m[:g.shape[0], px:px + g.shape[1]] |= g
    return m


def label_mask(s):
    return _set(LABEL, s, LABEL_SPACE, LABEL_GAP, LABEL_KERN, 10)



def _g(rows):
    """Glyph from rows of '#'/'.' -> bool array."""
    rows = [r for r in rows.strip('\n').split('\n')]
    rows = [r.strip() for r in rows]
    w = max(len(r) for r in rows)
    return np.array([[ch == '#' for ch in r.ljust(w, '.')] for r in rows], bool)



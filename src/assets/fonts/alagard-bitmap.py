#!/usr/bin/env python3
"""Alagard (Hewett Tsoi) -> bitmap glyph rows for src/ui/kinetic/alagard.js.

The TTF is drawn on a 16 px grid (64 units a pixel), so rasterised at 16 px with
anti-aliasing off every glyph is exact. Output rows use the pxfont.js format:
'top:row|row|...' where top is the first row below the cap line (11 px caps,
3 px descenders) and each row is padded to the glyph's advance minus its 1 px gap.

    python3 src/assets/fonts/alagard-bitmap.py > src/ui/kinetic/alagard.js
"""
import os, sys, json
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
TTF = os.path.join(HERE, 'alagard.ttf')
UNIT = 64
CAP = 11

tt = TTFont(TTF)
cmap = tt.getBestCmap()
hmtx = tt['hmtx']
font = ImageFont.truetype(TTF, 16)
asc = 12  # 768 / 64: the baseline sits 12 px under the em top
out = {}
for cp in sorted(cmap):
    ch = chr(cp)
    if cp < 33 or cp > 126:
        continue
    adv = hmtx[cmap[cp]][0] // UNIT
    img = Image.new('1', (adv + 8, 24), 0)
    d = ImageDraw.Draw(img)
    d.fontmode = '1'
    d.text((2, 2), ch, font=font, fill=1)
    W, H = img.size
    px = img.load()
    rows = [''.join('#' if px[x, y] else '.' for x in range(W)) for y in range(H)]
    ys = [y for y, r in enumerate(rows) if '#' in r]
    if not ys:
        continue
    xs = [x for x in range(W) if any(rows[y][x] == '#' for y in ys)]
    x0 = 2  # the pen origin: keep the left side bearing
    x1 = max(max(xs) + 1, x0 + adv - 1)
    top_img = 2 + asc - CAP  # image row of the cap line
    top = ys[0] - top_img
    body = [rows[y][x0:x1] for y in range(ys[0], ys[-1] + 1)]
    out[ch] = f'{top}:' + '|'.join(body)

print('// [v31 kinetic] Alagard by Hewett Tsoi (Pix3M), the 16 px medieval pixel font, as bitmap rows.')
print('// GENERATED by src/assets/fonts/alagard-bitmap.py from src/assets/fonts/alagard.ttf: do not edit by')
print('// hand. Format as in pxfont.js: "top:row|row|..." (top = rows below the 11 px cap line).')
print('export const ALAGARD_SRC = ' + json.dumps(out, ensure_ascii=False, indent=0).replace('\n', ' ') + ';')

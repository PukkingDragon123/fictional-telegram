def hop(ch):
    """same per-character hop as the woff2 font (pix.bounce_of): 1 = this letter sits 1 px higher."""
    if not ch.strip() or not (ch.isalnum()):
        return 0
    h = zlib.crc32(ch.encode()) & 0xffff
    return 1 if (h % 3) - 1 == 1 else 0


def mini(table, cap, hopping=True):
    out = {}
    for ch, rows in table.items():
        w = len(rows[0])
        assert all(len(r) == w for r in rows), ch
        assert len(rows) == cap, ch
        blank = '.' * w
        out[ch] = rows if not hopping else (rows + [blank]) if hop(ch) else ([blank] + rows)
    return out


def hi(src):
    gl = bg.make(src, 1, 0)
    TOP = 15  # cap 14 + 1 px hop
    out = {}
    for ch in CHARS:
        g = gl.get(ord(ch))
        if g is None:
            continue
        w = max(g.adv, g.x0 + (len(g.rows[0]) if g.rows else 0))
        bottom = min([0] + [g.ytop - len(g.rows)])
        H = TOP - bottom
        canvas = [['.'] * w for _ in range(H)]
        for r, row in enumerate(g.rows):
            y = TOP - g.ytop + r
            for c, v in enumerate(row):
                if v == '#' and 0 <= y < H:
                    canvas[y][g.x0 + c] = '#'
        rows = [''.join(r) for r in canvas]
        while len(rows) > 1 and '#' not in rows[-1]:
            rows.pop()
        if ch == ' ':
            rows = ['.' * w]
        out[ch] = rows
    return out


def js_table(t):
    lines = []
    for ch, rows in t.items():
        k = repr(ch) if ch not in ("'",) else '"\'"'
        if ch == '\\':
            k = "'\\\\'"
        lines.append('    %s: [%s],' % (k, ', '.join("'%s'" % r for r in rows)))
    return '\n'.join(lines)


